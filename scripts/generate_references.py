def _render_reference_mirror(filename: str, title: str, blurb: str) -> str:
    with open(os.path.join(REFERENCES, filename), "r", encoding="utf-8") as f:
        body = f.read()
    # Drop the reference's own H1; the docs page supplies the title.
    lines = body.splitlines()
    if lines and lines[0].startswith("# "):
        body = "\n".join(lines[1:]).lstrip("\n")
    return (
        f"<!-- Generated by scripts/generate_references.py from "
        f"skills/potato-tasks/references/{filename}. Do not edit by hand. -->\n\n"
        f"# {title}\n\n"
        f"{blurb} It ships with the `potato-tasks` skill:\n\n"
        "```\n"
        "/plugin marketplace add davidjurgens/potato-skill\n"
        "/plugin install potato-tasks@potato\n"
        "```\n\n"
        "---\n\n"
        + body
    )


OUTPUTS = {
    os.path.join(REFERENCES, "annotation-types.md"): render_annotation_types,
    os.path.join(REFERENCES, "config-keys.md"): render_config_keys,
    os.path.join(REFERENCES, "config-keys-nested.md"): render_config_keys_nested,
    DOCS_MIRROR: render_docs_mirror,
}

for _name, (_title, _blurb) in MIRRORED_REFERENCES.items():
    OUTPUTS[os.path.join(ROOT, "docs", _name)] = (
        lambda n=_name, t=_title, b=_blurb: _render_reference_mirror(n, t, b)
    )


def main() -> int:
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument(
        "--check", action="store_true", help="Verify without writing"
    )
    args = parser.parse_args()

    stale = []
    for path, render in OUTPUTS.items():
        payload = render()
        if args.check:
            try:
                with open(path, "r", encoding="utf-8") as f:
                    current = f.read()
            except OSError:
                stale.append(f"{os.path.relpath(path, ROOT)} (missing)")
                continue
            if current != payload:
                stale.append(os.path.relpath(path, ROOT))
        else:
            os.makedirs(os.path.dirname(path), exist_ok=True)
            with open(path, "w", encoding="utf-8") as f:
                f.write(payload)
            print(f"Wrote {os.path.relpath(path, ROOT)}")

    if args.check:
        if stale:
            print(
                "References are stale: "
                + ", ".join(stale)
                + "\nRegenerate with: python scripts/generate_references.py",
                file=sys.stderr,
            )
            return 1
        print("References are current.")
    return 0


if __name__ == "__main__":
    sys.exit(main())
